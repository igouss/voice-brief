use std::collections::BTreeMap;

use serde::Deserialize;
use ts_rs::TS;

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(rename = "Field")]
pub enum FieldKey {
    WeakestPart,
    Force,
    SmallestMove,
    Preserves,
    WouldReverseIt,
}

impl FieldKey {
    pub const ALL: [Self; 5] = [Self::WeakestPart, Self::Force, Self::SmallestMove, Self::Preserves, Self::WouldReverseIt];

    pub const fn title(self) -> &'static str {
        match self {
            Self::WeakestPart => "Weakest part",
            Self::Force => "Force",
            Self::SmallestMove => "Smallest move",
            Self::Preserves => "Preserves",
            Self::WouldReverseIt => "Would reverse it",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize, TS)]
#[ts(rename = "Claim")]
pub struct WireClaim {
    pub id: String,
    pub text: String,
    #[serde(default)]
    #[ts(optional)]
    pub said: Option<Vec<String>>,
    #[serde(default)]
    #[ts(optional)]
    pub added: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Deserialize, TS)]
pub struct Violation {
    pub violation: String,
    pub detail: serde_json::Value,
}

#[derive(Debug, Clone, PartialEq, Deserialize, TS)]
#[serde(untagged)]
pub enum Failure {
    Contract { violations: Vec<Violation> },
    NoReply { reason: String },
    Threw { error: String },
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, TS)]
#[serde(rename_all = "lowercase")]
pub enum ProposalKind {
    Place,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, TS)]
#[serde(rename_all = "lowercase")]
pub enum HandoffTarget {
    Clipboard,
}

#[derive(Debug, Clone, PartialEq, Deserialize, TS)]
#[serde(tag = "type")]
#[ts(rename = "ThreadEvent")]
pub enum Event {
    SessionStarted {
        pid: u32,
        project: String,
        #[serde(rename = "isCapturing", default)]
        #[ts(optional)]
        is_capturing: Option<bool>,
    },
    SetUp {
        unit: String,
        addon: String,
        settings: String,
    },
    TakeRecorded {
        take: String,
        stream: String,
        text: String,
        wav: String,
        ok: bool,
    },
    TakeSent {
        take: String,
    },
    TakeDeleted {
        take: String,
    },
    TranscriptCorrected {
        take: String,
        before: String,
        after: String,
    },
    JobSubmitted {
        base: u32,
        ctx: Vec<String>,
        dir: String,
    },
    JobFailed {
        #[serde(flatten)]
        failure: Failure,
    },
    ProposalMade {
        kind: ProposalKind,
        secs: f64,
        claims: BTreeMap<FieldKey, Vec<WireClaim>>,
        asked: BTreeMap<FieldKey, String>,
    },
    Accepted {
        revision: u32,
    },
    Rejected {},
    HandedOff {
        target: HandoffTarget,
        revision: u32,
        path: String,
    },
    #[serde(other)]
    #[ts(skip)]
    Unknown,
}

#[derive(Debug, Clone, PartialEq, Deserialize, TS)]
#[ts(rename = "ThreadLine")]
pub struct Line {
    pub n: u32,
    #[ts(type = "number")]
    pub at: u64,
    #[serde(flatten)]
    pub event: Event,
}

pub fn typescript() -> String {
    let cfg: ts_rs::Config = ts_rs::Config::new();
    let decls: [String; 9] = [
        FieldKey::decl(&cfg),
        WireClaim::decl(&cfg),
        <serde_json::Value as TS>::decl(&cfg),
        Violation::decl(&cfg),
        Failure::decl(&cfg),
        ProposalKind::decl(&cfg),
        HandoffTarget::decl(&cfg),
        Event::decl(&cfg),
        Line::decl(&cfg),
    ];
    let body: Vec<String> = decls.iter().map(|d| format!("export {d}\n")).collect();
    format!("{GENERATED_START}\n\n{}\n{GENERATED_END}\n", body.join("\n"))
}

pub const GENERATED_START: &str = "// @generated by `cargo run -q -p vb-thread --bin thread-ts -- <file>` from desktop/thread/src/wire.rs";
pub const GENERATED_END: &str = "// @end-generated";

pub fn splice(file: &str) -> String {
    let rest: &str = file.split_once(GENERATED_END).map_or(file, |(_, after)| after.strip_prefix('\n').unwrap_or(after));
    format!("{}{rest}", typescript())
}
